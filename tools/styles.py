#!/usr/bin/env python3
"""The style library's one source: styles/candidates.json.

  python3 tools/styles.py check   # contrast of every style, and the files below are up to date
  python3 tools/styles.py build   # writes styles/<name>/tokens.css for the library's styles,
                                  # the style data inside styles/gallery.html, and the token
                                  # blocks of templates/style.css (from the "clear" style)

Edit styles/candidates.json (to add a style, or move one in or out of the
library with "in_library"), then run build, then check. The tests run check.
Python 3.9 or later, no extra packages, so it runs on the Mac too.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STYLES = os.path.join(ROOT, "styles")
DATA = os.path.join(STYLES, "candidates.json")
GALLERY = os.path.join(STYLES, "gallery.html")
TEMPLATE = os.path.join(ROOT, "templates", "style.css")
DEFAULT = "clear"  # the style whose tokens templates/style.css starts with
START, END = "/*STYLES-DATA*/", "/*END-STYLES-DATA*/"

COLOURS = ["bg", "surface", "surface-2", "text", "muted", "border", "accent", "accent-text", "link",
           "good", "ok", "no", "on-good", "on-ok", "on-no", "danger"]
# (what, text colour, background colour, minimum contrast). WCAG 2.2 asks for
# 4.5:1 for normal text; every pair here can be text on that background.
PAIRS = [("main text on the page", "text", "bg", 4.5),
         ("main text on cards", "text", "surface", 4.5),
         ("main text on inputs", "text", "surface-2", 4.5),
         ("secondary text on the page", "muted", "bg", 4.5),
         ("secondary text on cards", "muted", "surface", 4.5),
         ("links on cards", "link", "surface", 4.5),
         ("links on the page", "link", "bg", 4.5),
         ("button text", "accent-text", "accent", 4.5),
         ("error text on cards", "danger", "surface", 4.5),
         ("error text on the page", "danger", "bg", 4.5),
         ("text on 'good'", "on-good", "good", 4.5),
         ("text on 'OK'", "on-ok", "ok", 4.5),
         ("text on 'no'", "on-no", "no", 4.5)]
REQUIRED = ["name", "title", "in_library", "source", "credit", "feel", "good_for",
            "font", "font_heading", "heading_weight", "radius", "radius_sm", "light", "dark"]


def rgb(hexcode):
    h = hexcode.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def luminance(hexcode):
    def lin(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(c) for c in rgb(hexcode))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def load():
    with open(DATA, encoding="utf-8") as f:
        return json.load(f)


def tokens_css(s):
    def block(mode, indent):
        t = s[mode]
        lines = ["%s--%s: %s;" % (indent, k, t[k]) for k in COLOURS]
        lines.append("%s--shadow: %s;" % (indent, t["shadow"]))
        return lines
    out = ["/* \"%s\" style tokens, from the playbook's styles/ folder. %s" % (s["title"], s["credit"]),
           "   Generated by tools/styles.py from styles/candidates.json: edit there, not here.",
           "   To use it: replace the two token blocks at the top of style.css with this file."]
    if s.get("font_link"):
        out.append("   Font: add to index.html's <head>: <link rel=\"stylesheet\" href=\"%s\">" % s["font_link"])
    out[-1] += " */"
    out += ["", ":root {"] + block("light", "  ") + [
        "  --radius: %s;" % s["radius"],
        "  --radius-sm: %s;" % s["radius_sm"],
        "  --font: %s;" % s["font"],
        "  --font-heading: %s;" % s["font_heading"],
        "  --heading-weight: %s;" % s["heading_weight"],
        "}", "", "/* Dark theme: used automatically when the device is in dark mode. */",
        "@media (prefers-color-scheme: dark) {", "  :root {"] + block("dark", "    ") + ["  }", "}", ""]
    return "\n".join(out)


def template_tokens(css):
    """The token blocks at the top of a style.css: from ':root {' to the first rule after them."""
    a = css.index(":root {")
    return a, css.index("\n* {", a)


def default_tokens(styles):
    s = [x for x in styles if x["name"] == DEFAULT][0]
    t = tokens_css(s)
    return t[t.index(":root {"):].rstrip("\n") + "\n"


def gallery_data(styles):
    return json.dumps(styles, ensure_ascii=False, separators=(",", ":"))


def problems(styles):
    found = []
    names = set()
    for s in styles:
        n = s.get("name", "?")
        for k in REQUIRED:
            if k not in s:
                found.append("%s: missing %s" % (n, k))
        if n in names:
            found.append("%s: name used twice" % n)
        names.add(n)
        if not re.match(r"^[a-z][a-z0-9-]*$", n):
            found.append("%s: name must be lower-case letters, digits and dashes" % n)
        for mode in ("light", "dark"):
            t = s.get(mode) or {}
            for k in COLOURS:
                if not re.match(r"^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$", str(t.get(k, ""))):
                    found.append("%s (%s): %s is not a #hex colour" % (n, mode, k))
            if "shadow" not in t:
                found.append("%s (%s): missing shadow" % (n, mode))
            if any(f.startswith(n) and "hex" in f for f in found):
                continue
            for what, fg, bg, minimum in PAIRS:
                c = contrast(t[fg], t[bg])
                if c < minimum:
                    found.append("%s (%s): %s is %.2f:1, needs %.1f:1 (%s on %s)"
                                 % (n, mode, what, c, minimum, t[fg], t[bg]))
    return found


def stale(styles):
    found = []
    library = [s for s in styles if s.get("in_library")]
    for s in library:
        p = os.path.join(STYLES, s["name"], "tokens.css")
        if not os.path.exists(p) or open(p, encoding="utf-8").read() != tokens_css(s):
            found.append("styles/%s/tokens.css is out of date: run python3 tools/styles.py build" % s["name"])
        if not os.path.exists(os.path.join(STYLES, s["name"], "DESIGN.md")):
            found.append("styles/%s/DESIGN.md is missing" % s["name"])
    for d in sorted(os.listdir(STYLES)):
        if os.path.isdir(os.path.join(STYLES, d)) and d not in [s["name"] for s in library]:
            found.append("styles/%s/ isn't in the library (in_library in candidates.json)" % d)
    css = open(TEMPLATE, encoding="utf-8").read()
    a, b = template_tokens(css)
    if css[a:b] != default_tokens(styles):
        found.append("templates/style.css's token blocks differ from the %s style: run python3 tools/styles.py build" % DEFAULT)
    g = open(GALLERY, encoding="utf-8").read()
    m = re.search(re.escape(START) + r"(.*?)" + re.escape(END), g, re.S)
    if not m or m.group(1) != gallery_data(styles):
        found.append("styles/gallery.html's style data is out of date: run python3 tools/styles.py build")
    return found


def build(styles):
    for s in styles:
        if s.get("in_library"):
            os.makedirs(os.path.join(STYLES, s["name"]), exist_ok=True)
            with open(os.path.join(STYLES, s["name"], "tokens.css"), "w", encoding="utf-8") as f:
                f.write(tokens_css(s))
    css = open(TEMPLATE, encoding="utf-8").read()
    a, b = template_tokens(css)
    with open(TEMPLATE, "w", encoding="utf-8") as f:
        f.write(css[:a] + default_tokens(styles) + css[b:])
    g = open(GALLERY, encoding="utf-8").read()
    if START not in g or END not in g:
        sys.exit("styles/gallery.html has no %s ... %s markers" % (START, END))
    a, rest = g.split(START, 1)
    _, b = rest.split(END, 1)
    with open(GALLERY, "w", encoding="utf-8") as f:
        f.write(a + START + gallery_data(styles) + END + b)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    styles = load()
    found = problems(styles)
    if cmd == "build":
        if found:
            print("\n".join(found))
            sys.exit("Not built: fix the problems above first.")
        build(styles)
        print("Built %d library styles and the gallery (%d styles)."
              % (sum(1 for s in styles if s.get("in_library")), len(styles)))
        return
    found += stale(styles)
    if found:
        print("\n".join(found))
        sys.exit(1)
    print("%d styles checked: contrast OK, files up to date." % len(styles))


if __name__ == "__main__":
    main()
